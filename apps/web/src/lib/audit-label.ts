const upperFirst = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);

export function auditLabel(code: string, dict: AuditDict): { text: string; known: boolean } {
  const whole = dict.action(code.replace(/[.]/g, '_'));
  if (whole !== null) return { text: whole, known: true };
  const parts = code.split(/[._]/).filter((p) => p !== '');
  const words = parts.map((p) => dict.word(p));
  if (parts.length === 0 || words.some((w) => w === null)) return { text: code, known: false };
  return { text: upperFirst(words.join(' ')), known: true };
}
