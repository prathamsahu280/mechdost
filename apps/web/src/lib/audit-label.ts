/**
 * Words for the codes the audit log stores (Admin → Audit log, hard rule 10): an entity ("setting") or an action
 * ("role.granted") is shown as a label in the page language, never as the raw code. Labels come from the locale
 * files: one wording per whole code when the word-by-word one reads badly (`auditAction`), else one per token
 * (`auditWord`). A code nobody has worded yet is shown as stored, marked unknown (the screen sets it in code style).
 * Pure: unit-tested with the real locale files.
 */
export interface AuditDict {
  /** The wording of one token ("granted"), or null. */
  word: (token: string) => string | null;
  /** The wording of a whole action code with dots as underscores ("role_granted"), or null. */
  action: (key: string) => string | null;
}

