/**
 * The database demo seed (`packages/db/seed/raipur-demo.json`, loaded by `pnpm db:seed:demo`) is derived from the
 * web demo data, so the catalogue API serves exactly what the local demo shows, Hindi included (hard rule 10).
 * This test rebuilds it and fails on drift. Regenerate after changing demo data:
 *   UPDATE_DEMO_SEED=1 pnpm --filter @mechdost/web exec vitest run test/demo-seed-fixture.test.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import en from '@mechdost/shared/i18n/en.json';
import hi from '@mechdost/shared/i18n/hi.json';
import {
  CATEGORY_KEYS,
  CATEGORY_SLUGS,
  DEMO_PRODUCTS,
  VEHICLE_TYPES_OF_FIT,
  type CategoryKey,
} from '../src/demo/catalogue';
import { AREA_HI, PRODUCT_HI, SHOP_HI } from '../src/demo/i18n/hi';
import { DEMO_PRODUCT_SPECS } from '../src/demo/product-specs';
import { DEMO_SHOPS } from '../src/demo/shops';
import { PIN_CENTROIDS } from '../src/demo/workshops';

const FIXTURE = fileURLToPath(new URL('../../../packages/db/seed/raipur-demo.json', import.meta.url));

/** Indicative HSN per category for the demo (GST 18 % on auto parts since 22 Sep 2025, decisions research). */
const HSN: Record<CategoryKey, string> = {
  tyres: '4011',
  lubricants: '2710',
  batteries: '8507',
  bearings: '8482',
  filters: '8421',
  spareParts: '8708',
  accessories: '8708',
  workshopTools: '8204',
  evEssentials: '8504',
};

/** Free stock per demo availability; "on request" has no buyable offer (the API shows it without a price). */
const STOCK = { in_stock: 12, low_stock: 2, on_request: 0 } as const;

const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

function buildFixture() {
  const categories = CATEGORY_KEYS.map((key, i) => ({
    slug: CATEGORY_SLUGS[key],
    name: en.categories[key],
    nameHi: hi.categories[key],
    description: en.home.categoryHints[key],
    descriptionHi: hi.home.categoryHints[key],
    sort: i + 1,
  }));
  const brands = [...new Set(DEMO_PRODUCTS.map((p) => p.brand))]
    .sort()
    .map((name) => ({ slug: slugify(name), name }));
  const products = DEMO_PRODUCTS.map((p) => {
    const h = PRODUCT_HI[p.slug];
    const specs = DEMO_PRODUCT_SPECS[p.slug];
    return {
      slug: p.slug,
      sku: p.sku,
      name: p.name,
      // Model-only names stay Latin in Hindi (allowed: brand and model names).
      nameHi: h?.name ?? p.name,
      brand: slugify(p.brand),
      category: CATEGORY_SLUGS[p.category],
      specSummary: p.spec,
      specSummaryHi: h?.spec ?? null,
      compatibility: p.compatibility,
      compatibilityHi: h?.compatibility ?? null,
      highlights: p.highlights,
      highlightsHi: h ? [...h.highlights] : [],
      mrpPaise: p.mrpPaise ?? p.pricePaise,
      hsn: HSN[p.category],
      gstRateBp: 1800,
      // Type-level fitment from the demo `fits` value only (decision 2026-11-12; EV is a fuel, no type).
      vehicleTypes: VEHICLE_TYPES_OF_FIT[p.fits],
      // Comparison data (decision 2026-11-13): typed attributes and the pack size, when the demo states them.
      ...(specs?.attributes ? { attributes: { ...specs.attributes } } : {}),
      ...(specs?.netQuantity ? { netQuantity: specs.netQuantity } : {}),
    };
  });
  const shops = DEMO_SHOPS.map((s, i) => ({
    slug: s.slug,
    name: s.name,
    nameHi: SHOP_HI[s.slug] ?? null,
    addressLine: `${s.area}, Raipur`,
    addressLineHi: `${AREA_HI[s.area] ?? s.area}, ${AREA_HI.Raipur ?? 'Raipur'}`,
    pincode: s.pincode,
    lat: s.lat,
    lng: s.lng,
    phone: `+9190000000${String(i + 1).padStart(2, '0')}`,
  }));
  // Every shop that stocks a category offers its products; the first is at the demo price, the others vary a
  // little so the "nearest covering shop sets the price" rule (spec 02) is visible across PIN codes.
  const offers = DEMO_PRODUCTS.flatMap((p) =>
    DEMO_SHOPS.filter((s) => s.categories.includes(p.category)).map((s, i) => ({
      shop: s.slug,
      sku: p.sku,
      sellingPaise: Math.round((p.pricePaise * (1 + 0.03 * i)) / 100) * 100,
      onHand: STOCK[p.availability],
      leadDays: p.leadDays,
    })),
  );
  const pincodes = Object.entries(PIN_CENTROIDS)
    .map(([pincode, c]) => ({ pincode, lat: c.lat, lng: c.lng }))
    .sort((a, b) => a.pincode.localeCompare(b.pincode));
  return {
    $comment: 'Generated by apps/web/test/demo-seed-fixture.test.ts from the web demo data. Demo only (Q21).',
    state: { code: 'CG', name: 'Chhattisgarh', gstStateCode: '22' },
    city: {
      code: 'RPR',
      slug: 'raipur',
      name: 'Raipur',
      nameHi: AREA_HI.Raipur ?? 'Raipur',
      lat: 21.227,
      lng: 81.64,
    },
    pincodes,
    categories,
    brands,
    products,
    shops,
    // Each shop delivers to every demo PIN; ₹40 delivery, lead days from the offer.
    coverage: { shippingPaise: 4000 },
    offers,
  };
}

describe('database demo seed fixture', () => {
  it('matches the web demo data (regenerate with UPDATE_DEMO_SEED=1)', () => {
    const built = buildFixture();
    // Compared as data: Prettier may reflow the file.
    if (process.env.UPDATE_DEMO_SEED === '1') writeFileSync(FIXTURE, `${JSON.stringify(built, null, 2)}\n`);
    expect(JSON.parse(readFileSync(FIXTURE, 'utf8'))).toEqual(built);
  });

  it('every shop PIN has a centroid and every product a Hindi spec', () => {
    const f = buildFixture();
    const pins = new Set(f.pincodes.map((p) => p.pincode));
    expect(f.shops.filter((s) => !pins.has(s.pincode))).toEqual([]);
    expect(f.products.filter((p) => !p.specSummaryHi || !p.compatibilityHi)).toEqual([]);
    expect(f.shops.filter((s) => !s.nameHi)).toEqual([]);
  });
});
