/**
 * Who may read each public table directly through Postgres (docs/research/rls-matrix.md). Writes are never granted:
 * the API is the only writer. `none` = deny-all (RLS on, no policy, no grant); every other value gets SELECT policies.
 *  - public: anon and authenticated read the published rows.
 *  - own: an authenticated user reads rows that belong to them.
 *  - partner: members of a shop (or workshop) read that shop's own rows.
 * A new table fails `rls.test.ts` until it is listed here, which forces the decision.
 */
